-- Dedicated Supabase project only. Run once in SQL Editor; this does not create participants.
-- All research tables live in an unexposed schema; no client-facing Data API.
create extension if not exists pgcrypto;
create schema if not exists diary;
revoke all on schema diary from public, anon, authenticated;

create table if not exists diary.participants (
  id uuid primary key default gen_random_uuid(),
  participant_code text not null unique check (length(participant_code) between 2 and 32),
  timezone text not null default 'America/Detroit',
  start_on date not null,
  consent_at timestamptz not null,
  opted_in boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists diary.contacts (
  participant_id uuid primary key references diary.participants(id) on delete cascade,
  phone_e164 text not null unique check (phone_e164 ~ '^\+[1-9][0-9]{7,14}$')
);
create table if not exists diary.sessions (
  id bigint generated by default as identity primary key,
  participant_id uuid not null references diary.participants(id) on delete cascade,
  study_day smallint not null check (study_day between 1 and 7),
  diary_date date not null,
  step smallint not null default 1 check (step between 1 and 6),
  status text not null default 'active' check (status in ('active','complete')),
  activity text,
  mood_earlier smallint check (mood_earlier between 1 and 5),
  mood_now smallint check (mood_now between 1 and 5),
  main_reason text,
  perceived_mood_effect text,
  functioning text,
  optional_note text check (length(optional_note) <= 280),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  unique(participant_id,study_day)
);
create table if not exists diary.inbound_events (
  provider_message_id text primary key,
  participant_id uuid not null references diary.participants(id) on delete cascade,
  received_at timestamptz not null default now()
);
create table if not exists diary.outbox (
  id bigint generated by default as identity primary key,
  participant_id uuid not null references diary.participants(id) on delete cascade,
  session_id bigint references diary.sessions(id) on delete cascade,
  kind text not null default 'question' check (kind in ('question','system')),
  content text not null,
  status text not null default 'pending' check (status in ('pending','sending','sent','failed','cancelled')),
  attempts integer not null default 0,
  available_at timestamptz not null default now(),
  claimed_at timestamptz,
  delivered_at timestamptz,
  last_error text,
  created_at timestamptz not null default now()
);
create index if not exists diary_outbox_due_idx on diary.outbox (status,available_at);
create index if not exists diary_sessions_participant_idx on diary.sessions (participant_id,study_day desc);

-- Defense in depth. The server uses a privileged server-side DB connection.
alter table diary.participants enable row level security;
alter table diary.contacts enable row level security;
alter table diary.sessions enable row level security;
alter table diary.inbound_events enable row level security;
alter table diary.outbox enable row level security;
revoke all on all tables in schema diary from public, anon, authenticated;
revoke all on all sequences in schema diary from public, anon, authenticated;
